import assert from "node:assert/strict";
import { chromium } from "playwright-core";
const baseUrl = process.env.BASE_URL ?? "http://127.0.0.1:3012";
assert.ok(["127.0.0.1", "localhost"].includes(new URL(baseUrl).hostname), "Use an isolated local test server");
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true });
const context = await browser.newContext();
const page = await context.newPage();
let release;
try {
  await page.goto(`${baseUrl}/admin`);
  await page.getByLabel("Contraseña administrativa").fill(process.env.E2E_ADMIN_PASSWORD ?? "product-test-password");
  await page.getByRole("button", { name: /Abrir panel/i }).click();
  await page.getByRole("heading", { name: "Estado del sistema" }).waitFor();
  await page.getByRole("button", { name: /Cartas/i }).click();
  await page.locator(".admin-player").first().waitFor();
  const searchResponse = page.waitForResponse((res) => res.url().includes("/api/admin/players?") && new URL(res.url()).searchParams.get("query") === "Mark Evans");
  await page.getByLabel("Buscar personaje o equipo").fill("Mark Evans");
  await searchResponse;
  let requested;
  let requestStarted = new Promise((resolve) => { requested = resolve; });
  let gate = new Promise((resolve) => { release = resolve; });
  let holdTeam = "original|Raimon";
  await page.route("**/api/admin/players?**", async (route) => {
    if (new URL(route.request().url()).searchParams.get("team") !== holdTeam) return route.continue();
    const held = gate;
    const signal = requested;
    const response = await route.fetch();
    signal();
    await held;
    await route.fulfill({ response });
  });
  await page.getByRole("button", { name: /Tier list Comparación visual/i }).click();
  await requestStarted;
  assert.equal(await page.locator(".tier-card").count(), 0, "Old search results must not be editable under the new team label");
  release();
  await page.locator(".tier-card").first().waitFor();
  assert.ok((await page.locator(".tier-card").evaluateAll((cards) => cards.map((c) => c.dataset.cardId))).every((id) => id.startsWith("original-raimon-")));
  const select = page.getByLabel("Filtrar por equipo");
  const options = await select.locator("option").evaluateAll((options) => options.map((option) => option.value));
  holdTeam = options[1];
  requestStarted = new Promise((resolve) => { requested = resolve; });
  gate = new Promise((resolve) => { release = resolve; });
  await select.selectOption(options[1]);
  await requestStarted;
  assert.equal(await page.locator(".tier-card").count(), 0);
  await select.selectOption(options[2]);
  await page.locator(".tier-card").first().waitFor();
  const currentIds = await page.locator(".tier-card").evaluateAll((cards) => cards.map((c) => c.dataset.cardId));
  const staleResponse = page.waitForResponse((res) => res.url().includes("/api/admin/players?") && new URL(res.url()).searchParams.get("team") === options[1]);
  release();
  await staleResponse;
  await page.waitForTimeout(100);
  assert.deepEqual(await page.locator(".tier-card").evaluateAll((cards) => cards.map((c) => c.dataset.cardId)), currentIds, "Late response must not replace the selected team");
  assert.equal(await select.inputValue(), options[2]);
  console.log("Admin request-race regression passed: hidden stale rows and ignored out-of-order response.");
} finally { release?.(); await browser.close(); }
